    private void jButton1ActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_jButton1ActionPerformed
        // TODO add your handling code here:
        try {
        String customer = jTextField1.getText();
        String product = jComboBox1.getSelectedItem().toString();
        double price = Double.parseDouble(jTextField2.getText());

        ProductCalculations calc = new ProductCalculations(price);

        double vat = calc.GetVat();
        double comm = calc.GetCommission();
        double total = calc.GetTotal();

        // Display message box
        String output = "Customer Name: " + customer + "\n" +
                        "Product: " + product + "\n" +
                        "VAT: R " + vat + "\n" +
                        "COMMISSION: R " + comm + "\n" +
                        "TOTAL: R " + total;

        javax.swing.JOptionPane.showMessageDialog(this, output);

        // Save to data.txt
        java.io.FileWriter fw = new java.io.FileWriter("data.txt", true);
        java.io.PrintWriter pw = new java.io.PrintWriter(fw);
        pw.println("DATA LOG");
        pw.println("****");
        pw.println("Customer Name: " + customer);
        pw.println("Product: " + product);
        pw.println("VAT: R " + vat);
        pw.println("COMMISSION: R " + comm);
        pw.println("TOTAL: R " + total);
        pw.println("****");
        pw.close();
        
    } catch (NumberFormatException e) {
        javax.swing.JOptionPane.showMessageDialog(this, "Please enter a valid number for the price.");
    } catch (Exception e) {
        javax.swing.JOptionPane.showMessageDialog(this, "Error saving file.");
    }
    }//GEN-LAST:event_jButton1ActionPerformed

